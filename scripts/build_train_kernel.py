def _encode_rows(study_labels, study_fold, study_weights, study_filled):
    """{study_id: "fold|labels|weights|filled"} -- see the decoder in the
    generated kernel. Weights list only non-1.0 cells as col:weight."""
    rows = {}
    for sid, labels in study_labels.items():
        w = study_weights.get(sid)
        w_str = ",".join(f"{j}:{v:g}" for j, v in enumerate(w) if v != 1.0) if w else ""
        rows[sid] = "|".join([
            str(study_fold[sid]) if sid in study_fold else "",
            ",".join(str(int(x)) for x in labels),
            w_str,
            ",".join(str(j) for j in study_filled.get(sid, [])),
        ])
    return rows


