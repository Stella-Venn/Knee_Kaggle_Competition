    study_ids_all = list(labels_npz["study_ids"])
    labels_all = labels_npz["labels"]
    weights_all = labels_npz["weights"]
    source_all = labels_npz["source"]
    SOURCE_UNMENTIONED = 4  # final_labels.SOURCE_UNMENTIONED
    idx_by_id = {sid: i for i, sid in enumerate(study_ids_all)}

    folds = np.load(ROOT / "data" / "processed" / "cv_folds.npz", allow_pickle=True)
    fold_by_id = dict(zip(folds["study_ids"].tolist(), folds["fold"].tolist()))

    if args.pilot_only:
        wanted_ids = [
            l.strip() for l in (ROOT / "data" / "splits" / "pilot_study_ids.txt").read_text().splitlines()
            if l.strip()
        ]
        out_dir = ROOT / "kaggle_kernels" / "train_pilot"
        kernel_id, title = "your-kaggle-username/rsna-knee-train-pilot", "RSNA Knee - Train Pilot"
        kernel_slugs = PILOT_KERNEL_SLUGS
    else:
        wanted_ids = folds["study_ids"].tolist()  # the full 4349-study mined pool
        out_dir = ROOT / "kaggle_kernels" / "train_full"
        kernel_id, title = "your-kaggle-username/rsna-knee-train-full", "RSNA Knee - Train Full"
        kernel_slugs = FULL_KERNEL_SLUGS

    study_labels = {sid: labels_all[idx_by_id[sid]].tolist() for sid in wanted_ids if sid in idx_by_id}
    study_fold = {sid: fold_by_id[sid] for sid in wanted_ids if sid in fold_by_id}
    study_filled = {
        sid: [int(j) for j in np.where(source_all[idx_by_id[sid]] == SOURCE_UNMENTIONED)[0]]
        for sid in wanted_ids if sid in idx_by_id and (source_all[idx_by_id[sid]] == SOURCE_UNMENTIONED).any()
    }
    study_weights = {
        sid: [round(float(x), 4) for x in weights_all[idx_by_id[sid]]]
        for sid in wanted_ids if sid in idx_by_id and (weights_all[idx_by_id[sid]] != 1.0).any()
    }
