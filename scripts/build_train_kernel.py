def _shift_zero_fill(vol, shifts):
    """Shift a 3D array by integer (dz, dy, dx), zero-filling what moves in
    (0 is also the crop/pad fill value, so this adds no new edge artifact)."""
    out = np.zeros_like(vol)
    src, dst = [], []
    for s, n in zip(shifts, vol.shape):
        if s >= 0:
            src.append(slice(0, n - s)); dst.append(slice(s, n))
        else:
            src.append(slice(-s, n)); dst.append(slice(0, n + s))
    out[tuple(dst)] = vol[tuple(src)]
    return out


def augment_volume(vol, rng):
    """Train-time only (2026-09-24 -- the previous run had NO augmentation and
    overfit from ~epoch 18). Volumes are per-volume percentile-normalized to
    [0, 1]. Gamma/contrast/brightness jitter mimics scanner-to-scanner
    contrast differences (domain shift across scanners); small shifts
    (<= 6 mm in-plane, 1 slice) add position robustness. No flips: which
    array axis is medial/lateral isn't verified per plane, and a wrong flip
    would teach nothing useful at best."""
    vol = np.clip(vol, 0.0, 1.0) ** rng.uniform(0.8, 1.25)
    vol = vol * rng.uniform(0.85, 1.15) + rng.uniform(-0.05, 0.05)
    if rng.random() < 0.3:
        vol = vol + rng.normal(0.0, 0.02, size=vol.shape).astype(np.float32)
    shifts = (int(rng.integers(-1, 2)), int(rng.integers(-12, 13)), int(rng.integers(-12, 13)))
    return _shift_zero_fill(np.clip(vol, 0.0, 1.0).astype(np.float32), shifts)


class PilotCachedDataset(Dataset):
    def __init__(self, study_ids, labels, study_to_cache_dir, target_shape=(32, 256, 256), planes=PLANES,
                 weights=None, augment=False):
        labels = np.asarray(labels)
        assert labels.shape == (len(study_ids), len(LABEL_COLUMNS))
        self.study_ids = list(study_ids)
        self.labels = labels
        self.weights = (np.ones(labels.shape, dtype=np.float32) if weights is None
                        else np.asarray(weights, dtype=np.float32))
        self.augment = augment
        self.study_to_cache_dir = study_to_cache_dir
        self.target_shape = target_shape
        self.planes = planes

    def __len__(self):
        return len(self.study_ids)

    def __getitem__(self, idx):
        study_id = self.study_ids[idx]
        cache_dir = self.study_to_cache_dir.get(study_id)
        study_dir = os.path.join(cache_dir, study_id) if cache_dir else None
        by_plane = {}
        if study_dir and os.path.isdir(study_dir):
            for fname in os.listdir(study_dir):
                if not fname.endswith(".json"):
                    continue
                with open(os.path.join(study_dir, fname)) as f:
                    meta = json.load(f)
                by_plane[meta["plane"]] = fname[: -len(".json")] + ".npy"

        channels, plane_present = [], []
        for plane in self.planes:
            npy_name = by_plane.get(plane)
            if npy_name is None:
                channels.append(np.zeros(self.target_shape, dtype=np.float32))
                plane_present.append(False)
            else:
                volume = center_crop_or_pad(np.load(os.path.join(study_dir, npy_name)), self.target_shape)
                if self.augment:
                    volume = augment_volume(volume, np.random.default_rng())
                channels.append(volume)
                plane_present.append(True)
        image = np.stack(channels, axis=0)

        label = self.labels[idx].astype(np.float32)
        label_mask = label != MASKED
        return {
            "study_id": study_id,
            "image": torch.from_numpy(image),
            "label": torch.from_numpy(label),
            "label_mask": torch.from_numpy(label_mask),
            "label_weight": torch.from_numpy(self.weights[idx]),
            "plane_present": torch.tensor(plane_present, dtype=torch.bool),
        }


def find_cache_dirs():
    """Bounded search under /kaggle/input for EVERY attached volume-cache
    kernel's output (there can be several -- the pilot alone, or the pilot
    plus 6 shards for a full-dataset run) -- not hardcoding exact mount
    paths, since kernel_sources mount naming hasn't been verified beyond
    what earlier runs actually found . Once a match is
    found, doesn't descend further into it (no reason to keep walking a
    cache dir's thousands of per-study subdirectories). Never walks past 6
    levels deep or prints the full tree (a prior kernel got flooded/likely
    hurt by os.walk-and-print over the full competition DICOM tree -- see
    kaggle_kernels/translate_reports's comment).
    """
    found = []
    for root, dirs, files in os.walk("/kaggle/input", followlinks=True):
        depth = root[len("/kaggle/input"):].count(os.sep)
        if depth >= 6:
            dirs[:] = []
            continue
        if os.path.basename(root) == TAG and "volume_cache" in root:
            found.append(root)
            dirs[:] = []  # don't descend into a matched cache dir's study subfolders
    if not found:
        raise SystemExit(
            "Could not find any attached volume-cache kernel output under /kaggle/input -- "
            "check kernel_sources in kernel-metadata.json and that those kernels' status is COMPLETE."
        )
    return found


def build_study_index(cache_dirs):
    """study_id -> cache_dir, built once by listing each cache dir's immediate
    subdirectories (one per cached study). A study_id appearing in more than
    one cache dir (shouldn't happen -- shards are disjoint by construction)
    keeps whichever is found first.
    """
    index = {}
    for d in cache_dirs:
        for name in os.listdir(d):
            if os.path.isdir(os.path.join(d, name)):
                index.setdefault(name, d)
    return index


