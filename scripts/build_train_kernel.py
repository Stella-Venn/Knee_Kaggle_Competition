class ModelEMA:
    """Exponential moving average of the weights, used for validation and
    checkpoints (2026-09-24). The previous run's val AUC swung +-0.02
    epoch to epoch, so "best single epoch" was partly luck; averaged
    weights are smoother and usually generalize a bit better. BatchNorm
    buffers are copied, not averaged."""

    def __init__(self, model, decay):
        self.module = copy.deepcopy(model).eval()
        self.decay = decay
        self.param_names = {k for k, _ in model.named_parameters()}
        for p in self.module.parameters():
            p.requires_grad_(False)

    @torch.no_grad()
    def update(self, model):
        ema_sd, sd = self.module.state_dict(), model.state_dict()
        for k, v in ema_sd.items():
            if v.dtype.is_floating_point and k in self.param_names:
                v.mul_(self.decay).add_(sd[k].detach(), alpha=1 - self.decay)
            else:
                v.copy_(sd[k])


def warmup_cosine(step, total_steps, warmup_steps, floor=0.02):
    """LR multiplier: linear warm-up from 10% over `warmup_steps`, then cosine
    decay to `floor` (the previous run used a constant LR)."""
    if step < warmup_steps:
        return 0.1 + 0.9 * step / max(1, warmup_steps)
    t = (step - warmup_steps) / max(1, total_steps - warmup_steps)
    return floor + (1 - floor) * 0.5 * (1 + math.cos(math.pi * min(t, 1.0)))


def train_one_epoch(model, loader, optimizer, scheduler, scaler, ema, loss_fn, device):
    """Returns (mean batch loss, seconds waiting on data, seconds computing) --
    the split says whether the GPU or the data loader is the bottleneck."""
    model.train()
    total_loss, n_batches = 0.0, 0
    t_data = t_compute = 0.0
    use_amp = device == "cuda"
    t = time.time()
    for batch in loader:
        t_data += time.time() - t
        t = time.time()
        image = batch["image"].to(device, non_blocking=True)
        plane_present = batch["plane_present"].to(device)
        label = batch["label"].to(device)
        label_mask = batch["label_mask"].to(device)
        weight = batch["label_weight"].to(device)
        optimizer.zero_grad(set_to_none=True)
        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=use_amp):
            logits = model(image, plane_present)
        loss = loss_fn(logits.float(), label, label_mask, weight)
        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()
        scheduler.step()
        ema.update(model)
        total_loss += loss.item()
        n_batches += 1
        if use_amp:
            torch.cuda.synchronize()
        t_compute += time.time() - t
        t = time.time()
    return total_loss / max(n_batches, 1), t_data, t_compute


@torch.no_grad()
def predict(model, loader, device):
    model.eval()
    study_ids, all_labels, all_probs, all_masks = [], [], [], []
    for batch in loader:
        image = batch["image"].to(device)
        plane_present = batch["plane_present"].to(device)
        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=device == "cuda"):
            logits = model(image, plane_present)
        probs = torch.sigmoid(logits.float())
        study_ids.extend(batch["study_id"])
        all_labels.append(batch["label"].numpy())
        all_probs.append(probs.cpu().numpy())
        all_masks.append(batch["label_mask"].numpy())
    return (study_ids, np.concatenate(all_labels, axis=0),
            np.concatenate(all_probs, axis=0), np.concatenate(all_masks, axis=0))


