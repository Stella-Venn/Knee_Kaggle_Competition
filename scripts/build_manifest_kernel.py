"""Generate kaggle_kernels/dicom_manifest/manifest_kernel.py: the header-manifest
kernel with src/data/dicom_manifest.py embedded verbatim, so the code that runs on
Kaggle is the code the tests cover.

Usage: python scripts/build_manifest_kernel.py [--limit N]
  --limit N   only the first N training series (plus all test series), for a timing
              smoke run before the full pass. Omit for everything.
Then: kaggle kernels push -p kaggle_kernels/dicom_manifest
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "kaggle_kernels" / "dicom_manifest"

MAIN = '''

# ---------------------------------------------------------------------------
# Kernel driver (everything above this line is src/data/dicom_manifest.py)
# ---------------------------------------------------------------------------
import csv
import time
from multiprocessing import Pool

COMP = "/kaggle/input/competitions/rsna-knee-abnormality-detection"
OUT = "/kaggle/working"
LIMIT_TRAIN_SERIES = __LIMIT__
N_PROC = 4


def _series_task(args):
    split, study, series = args
    d = os.path.join(COMP, split, study, series)
    try:
        paths = sorted(os.path.join(d, f) for f in os.listdir(d) if f.endswith(".dcm"))
        headers = [read_slice_header(p) for p in paths]
        row = summarize_series(headers, study, series)
        row["split"] = split
        return row, None
    except Exception as e:  # keep going; report the failure
        return None, (split, study, series, repr(e))


def _read_series_csv(name):
    with open(os.path.join(COMP, name), newline="") as f:
        return list(csv.DictReader(f))


def main():
    tasks, csv_meta = [], {}
    for split, name in (("test_series", "test_series.csv"), ("train_series", "train_series.csv")):
        rows = _read_series_csv(name)
        if split == "train_series" and LIMIT_TRAIN_SERIES:
            rows = rows[:LIMIT_TRAIN_SERIES]
        for r in rows:
            tasks.append((split, r["StudyInstanceUID"], r["SeriesInstanceUID"]))
            csv_meta[(r["StudyInstanceUID"], r["SeriesInstanceUID"])] = r
    print(f"{len(tasks)} series to read (limit={LIMIT_TRAIN_SERIES})", flush=True)

    results, errors = [], []
    t0 = time.time()
    with Pool(N_PROC) as pool:
        for i, (row, err) in enumerate(pool.imap_unordered(_series_task, tasks, chunksize=4), 1):
            if row:
                m = csv_meta[(row["StudyInstanceUID"], row["SeriesInstanceUID"])]
                for k in ("Fluid_Sensitive", "Fat_Suppression", "Anatomical_Plane"):
                    row["csv_" + k] = m.get(k)
                results.append(row)
            else:
                errors.append(err)
            if i % 1000 == 0 or i == len(tasks):
                el = time.time() - t0
                print(f"{i}/{len(tasks)} series, {el/60:.1f} min, eta {(len(tasks)-i)*el/i/60:.1f} min, "
                      f"errors {len(errors)}", flush=True)

    results.sort(key=lambda r: (r["split"], r["StudyInstanceUID"], r["SeriesInstanceUID"]))
    fields = list(results[0].keys())
    with open(os.path.join(OUT, "series_manifest.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(results)
    studies = build_study_manifest(results)
    with open(os.path.join(OUT, "study_manifest.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(studies[0].keys()))
        w.writeheader()
        w.writerows(studies)
    with open(os.path.join(OUT, "errors.json"), "w") as f:
        json.dump(errors, f)
    print(f"done: {len(results)} series, {len(studies)} studies, {len(errors)} errors, "
          f"{(time.time()-t0)/60:.1f} min", flush=True)


if __name__ == "__main__":
    main()
'''

HEADER = '"""Build the DICOM header manifest over the competition data. GENERATED by\nscripts/build_manifest_kernel.py -- edit src/data/dicom_manifest.py, not this file."""\nimport json\nimport subprocess\nimport sys\ntry:\n    import pydicom  # noqa: F401\nexcept ImportError:\n    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "pydicom"], check=True)\n\n'


def main():
    limit = None
    if "--limit" in sys.argv:
        limit = int(sys.argv[sys.argv.index("--limit") + 1])
    module_src = (ROOT / "src" / "data" / "dicom_manifest.py").read_text()
    # drop the module docstring's leading position; keep the rest verbatim
    code = HEADER + module_src + MAIN.replace("__LIMIT__", repr(limit))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "manifest_kernel.py").write_text(code)
    meta = {
        "id": "your-kaggle-username/rsna-knee-dicom-header-manifest",
        "title": "RSNA Knee - DICOM Header Manifest",
        "code_file": "manifest_kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": ["rsna-knee-abnormality-detection"],
        "kernel_sources": [],
    }
    (OUT_DIR / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"wrote {OUT_DIR}/manifest_kernel.py (limit={limit})")


if __name__ == "__main__":
    main()
