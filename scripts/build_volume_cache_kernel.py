"""Generate kaggle_kernels/volume_cache_pilot/volume_cache_kernel.py: the
pilot-scale volume-caching kernel, embedding src/data/dicom_manifest.py and
src/data/volume_loader.py verbatim (same "code that runs is the code the
tests cover" approach as scripts/build_manifest_kernel.py), plus a hand-kept
copy of dataset.py's select_canonical_series/spacing_tag (those two are pure,
torch-free functions -- kept out of a full dataset.py import so this kernel
doesn't need torch or label_mining.final_labels).

Pilot scope, and why: not the full 4407-study training set in one kernel run.
This caches (at most) 558 studies -- a stratified 500 from the mined-label
pool (100 per CV fold, data/splits/pilot_study_ids.txt, see scripts that
built it) plus all 58 gold studies (so evaluate_on_gold has real data to run
against once a model exists). Real timing/output-size numbers from this run
decide how to scale to the full dataset (sharded Kaggle kernel runs into a
[redacted: note about institution-specific computing resources]

**Bounded output shape (2026-09-22, real Kaggle failure)**: the first
558-study attempt at resample-only output (no crop/pad) died mid-run --
ERROR status, ~200/558 studies processed, ~10GB transferred, ~16.6MB/series
average, roughly 2x this project's earlier (32,256,256)-based size estimate,
because resampling to a fixed physical SPACING leaves array size proportional
to each study's actual field of view, unbounded. `TARGET_SHAPE` now bounds
every cached array to a fixed size via `center_crop_or_pad` (same fix applied
to the local scripts/precompute_volume_cache.py), so total output size scales
predictably with study count rather than with the long tail of unusually
large series (real measured distribution: H/W p50~320, p99 up to 460-640).

**Sharding for the rest of the dataset (2026-09-22)**: once the pilot's real numbers were in
(13GB/558 studies, 0 errors), scaling to the remaining ~3849 mined studies needed splitting
across multiple kernel runs -- one kernel's output can't hold the full ~101GB. `--shard N`
generates a kernel for `data/splits/cache_shard_N_study_ids.txt` (scripts/select_cache_shards.py,
700 studies/shard, ~16.3GB/shard at the measured rate) instead of the 558-study pilot list, with
[redacted: detail about the data challenge this code was written for]

Usage: python scripts/build_volume_cache_kernel.py [--shard N]
Then: kaggle kernels push -p kaggle_kernels/volume_cache_pilot   (or volume_cache_shard_N)
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TARGET_SPACING = (3.0, 0.5, 0.5)
TARGET_SHAPE = (32, 256, 256)  # bounds file size; see module docstring, "Bounded output shape"

HEADER = '''"""Cache resampled, normalized volumes for a pilot subset of training studies.
GENERATED by scripts/build_volume_cache_kernel.py -- edit src/data/dicom_manifest.py
or src/data/volume_loader.py, not this file, for anything beyond the driver below.
"""
import json
import os
import subprocess
import sys
import time
from multiprocessing import Pool

try:
    import pydicom  # noqa: F401
except ImportError:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "pydicom"], check=True)

import numpy as np

'''

# Hand-kept copies of dataset.py's two pure, torch-free helpers (not importing
# dataset.py itself here -- it pulls in torch and label_mining.final_labels,
# neither needed by this kernel). Keep these in sync with src/data/dataset.py.
DATASET_HELPERS = '''

PLANES = ("Sagittal", "Coronal", "Axial")


def spacing_tag(target_spacing):
    return "x".join(f"{v:g}" for v in target_spacing)


def select_canonical_series(series_rows, planes=PLANES, plane_key="csv_Anatomical_Plane",
                             n_slices_key="n_slices", series_id_key="SeriesInstanceUID"):
    best = {}
    for row in series_rows:
        plane = row.get(plane_key)
        if plane not in planes:
            continue
        n = int(row[n_slices_key])
        if plane not in best or n > best[plane][0]:
            best[plane] = (n, row[series_id_key])
    return {plane: series_id for plane, (_, series_id) in best.items()}

'''

MAIN = '''

# ---------------------------------------------------------------------------
# Kernel driver
# ---------------------------------------------------------------------------
COMP = "/kaggle/input/competitions/rsna-knee-abnormality-detection"
OUT = "/kaggle/working"
TARGET_SPACING = __TARGET_SPACING__
TARGET_SHAPE = __TARGET_SHAPE__  # crop/pad after resampling -- bounds file size; see module docstring
TAG = spacing_tag(TARGET_SPACING)
CACHE_DIR = os.path.join(OUT, "volume_cache", TAG)
N_PROC = 4

PILOT_STUDY_IDS = __PILOT_IDS__


def _n_dcm_files(path):
    try:
        return sum(1 for f in os.listdir(path) if f.endswith(".dcm"))
    except FileNotFoundError:
        return 0


# Top-level (not a closure over main()'s locals) and takes its input
# explicitly as an argument -- required for multiprocessing under the
# "spawn" start method (macOS/Windows default, and not guaranteed to be
# "fork" on Kaggle's Linux either): a child process re-imports this module
# fresh and only ever sees what's at module scope or passed in as a picklable
# argument, never a parent process's local variables. A nested closure passed
# to Pool.imap_unordered fails immediately with "can't pickle local object"
# -- caught locally against a synthetic fake-competition tree before this
# kernel was ever pushed to Kaggle .
def _task(args):
    study_id, rows = args
    study_dir = os.path.join(COMP, "train_series", study_id)
    candidates = []
    for r in rows:
        series_dir = os.path.join(study_dir, r["SeriesInstanceUID"])
        n = _n_dcm_files(series_dir)
        if n == 0:
            continue
        candidates.append({
            "SeriesInstanceUID": r["SeriesInstanceUID"],
            "n_slices": n,
            "csv_Anatomical_Plane": r["Anatomical_Plane"],
        })
    canonical = select_canonical_series(candidates)

    out_study_dir = os.path.join(CACHE_DIR, study_id)
    n_ok, errors = 0, []
    for plane, series_id in canonical.items():
        series_dir = os.path.join(study_dir, series_id)
        try:
            result = load_series_volume(series_dir)
            resampled, achieved = resample_volume(
                result.volume,
                (result.slice_spacing, result.row_spacing, result.col_spacing),
                TARGET_SPACING,
            )
            normalized = normalize_intensity(resampled)
            bounded = center_crop_or_pad(normalized, TARGET_SHAPE)
            os.makedirs(out_study_dir, exist_ok=True)
            np.save(os.path.join(out_study_dir, series_id + ".npy"), bounded)
            with open(os.path.join(out_study_dir, series_id + ".json"), "w") as f:
                json.dump({
                    "plane": result.plane, "target_spacing": list(TARGET_SPACING),
                    "achieved_spacing": list(achieved), "resampled_shape": list(normalized.shape),
                    "shape": list(bounded.shape),
                    "orientation_consistent": result.orientation_consistent,
                    "uniform_spacing": result.uniform_spacing,
                }, f)
            n_ok += 1
        except Exception as e:
            errors.append((study_id, plane, series_id, repr(e)))
    return study_id, n_ok, len(canonical), errors


def main():
    os.makedirs(CACHE_DIR, exist_ok=True)
    print(f"Caching {len(PILOT_STUDY_IDS)} pilot studies to {CACHE_DIR} "
          f"(target_spacing={TARGET_SPACING})", flush=True)

    import csv
    series_by_study = {}
    with open(os.path.join(COMP, "train_series.csv"), newline="") as f:
        for row in csv.DictReader(f):
            if row["StudyInstanceUID"] in PILOT_STUDY_IDS:
                series_by_study.setdefault(row["StudyInstanceUID"], []).append(row)
    print(f"{sum(len(v) for v in series_by_study.values())} series across "
          f"{len(series_by_study)}/{len(PILOT_STUDY_IDS)} pilot studies found in train_series.csv",
          flush=True)

    t0 = time.time()
    all_errors = []
    n_series_cached = 0
    tasks = list(series_by_study.items())
    with Pool(N_PROC) as pool:
        for i, (study_id, n_ok, n_canonical, errors) in enumerate(pool.imap_unordered(_task, tasks), 1):
            n_series_cached += n_ok
            all_errors.extend(errors)
            if i % 25 == 0 or i == len(tasks):
                elapsed = time.time() - t0
                eta = (len(tasks) - i) * elapsed / i / 60
                print(f"{i}/{len(tasks)} studies, {n_series_cached} series cached, "
                      f"{len(all_errors)} errors, {elapsed/60:.1f} min elapsed, ETA {eta:.1f} min",
                      flush=True)

    with open(os.path.join(OUT, "errors.json"), "w") as f:
        json.dump(all_errors, f)
    print(f"\\nDone: {n_series_cached} series cached across {len(tasks)} studies, "
          f"{len(all_errors)} errors, {(time.time()-t0)/60:.1f} min total", flush=True)


if __name__ == "__main__":
    main()
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shard", type=int, default=None,
                     help="cache data/splits/cache_shard_N_study_ids.txt instead of the pilot list")
    args = ap.parse_args()

    if args.shard is None:
        ids_path = ROOT / "data" / "splits" / "pilot_study_ids.txt"
        out_dir = ROOT / "kaggle_kernels" / "volume_cache_pilot"
        kernel_id = "your-kaggle-username/rsna-knee-volume-cache-pilot"
        title = "RSNA Knee - Volume Cache Pilot"
    else:
        ids_path = ROOT / "data" / "splits" / f"cache_shard_{args.shard}_study_ids.txt"
        out_dir = ROOT / "kaggle_kernels" / f"volume_cache_shard_{args.shard}"
        kernel_id = f"your-kaggle-username/rsna-knee-volume-cache-shard-{args.shard}"
        title = f"RSNA Knee - Volume Cache Shard {args.shard}"

    dicom_manifest_src = (ROOT / "src" / "data" / "dicom_manifest.py").read_text()
    volume_loader_src = (ROOT / "src" / "data" / "volume_loader.py").read_text()
    # strip volume_loader's own import of dicom_manifest -- those names are
    # already in scope from the embedded dicom_manifest source above it.
    volume_loader_src = volume_loader_src.replace(
        "from data.dicom_manifest import plane_from_orientation, read_slice_header, slice_normal\n", ""
    )

    study_ids = [s for s in ids_path.read_text().splitlines() if s.strip()]
    if len(study_ids) < 2:
        raise SystemExit(f"id list at {ids_path} looks empty/too short ({len(study_ids)})")

    code = (
        HEADER
        + dicom_manifest_src
        + "\n\n" + volume_loader_src
        + DATASET_HELPERS
        + MAIN.replace("__TARGET_SPACING__", repr(TARGET_SPACING))
               .replace("__TARGET_SHAPE__", repr(TARGET_SHAPE))
               .replace("__PILOT_IDS__", "set(" + repr(study_ids) + ")")
    )

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "volume_cache_kernel.py").write_text(code)

    meta = {
        "id": kernel_id,
        "title": title,
        "code_file": "volume_cache_kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,  # CPU-bound (pydicom decode + scipy resample); frees the GPU quota
        "enable_internet": True,  # for `pip install pydicom`
        "dataset_sources": [],
        "competition_sources": ["rsna-knee-abnormality-detection"],
        "kernel_sources": [],
    }
    (out_dir / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"wrote {out_dir}/volume_cache_kernel.py ({len(study_ids)} studies)")


if __name__ == "__main__":
    main()
