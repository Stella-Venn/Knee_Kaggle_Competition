def build_code(driver=None):
    predict_src = _src("src/inference/predict.py", strip=[
        "from data.dataset import select_canonical_series\n",
        "from data.volume_loader import (\n    center_crop_or_pad,\n    load_series_volume,\n"
        "    normalize_intensity,\n    resample_volume,\n)\n",
        "from utils.constants import LABEL_COLUMNS\n",
    ])
    return "\n\n".join([
        HEADER.replace("__LABEL_COLUMNS__", repr(LABEL_COLUMNS)),
        _src("src/data/dicom_manifest.py"),
        _src("src/data/volume_loader.py", strip=[
            "from data.dicom_manifest import plane_from_orientation, read_slice_header, slice_normal\n"]),
        'PLANES = ("Sagittal", "Coronal", "Axial")\n\n\n'
        + _function_source("src/data/dataset.py", "select_canonical_series"),
        _src("src/models/backbone3d.py"),
        _src("src/models/knee_model.py", strip=["from models.backbone3d import Simple3DCNN\n"]),
        _src("src/inference/validate_submission.py", strip=["from utils.constants import LABEL_COLUMNS\n"]),
        predict_src,
        driver if driver is not None else DRIVER.replace("__WEIGHTS_DATASET__", WEIGHTS_DATASET),
    ])


